async function seedCompleteTKPI() {
  console.log("🚀 Memulai upload data lengkap resmi TKPI 2019 Kemenkes RI ke Firestore...");
  const colRef = collection(db, "master_nilai_gizi");

  // 1. Bersihkan koleksi lama
  const snapshot = await getDocs(colRef);
  console.log(`Mengosongkan ${snapshot.docs.length} data lama di master_nilai_gizi...`);
  for (const d of snapshot.docs) {
    await deleteDoc(doc(db, "master_nilai_gizi", d.id));
  }

  // 2. Tulis data baru lengkap TKPI 2019 dengan pure UUID
  console.log(`Mengunggah ${COMPLETE_TKPI_2019.length} data bahan pangan lengkap TKPI 2019...`);
  let no = 1;
  for (const item of COMPLETE_TKPI_2019) {
    const docId = crypto.randomUUID();
    await setDoc(doc(db, "master_nilai_gizi", docId), {
      ...item,
      no: no++,
      updatedAt: new Date().toISOString()
    });
    console.log(`✓ [${item.code}] ${item.name} (${item.category}) tersimpan dengan ID: ${docId}`);
  }

  console.log("🎉 SELESAI! Seluruh data resmi TKPI 2019 Kemenkes RI berhasil tersimpan ke Cloud Firestore (ginofest-2026)!");
  process.exit(0);
}

seedCompleteTKPI().catch(err => {
  console.error("Gagal melakukan seeding:", err);
  process.exit(1);
});
